from tools.router import execute_tool


# ============================================================
# HERRAMIENTAS PERMITIDAS
# ============================================================

ALLOWED_TOOLS = {
    # --------------------------------------------------------
    # APLICACIONES
    # --------------------------------------------------------

    "open_notepad",

    "open_youtube",


    # --------------------------------------------------------
    # YOUTUBE
    # --------------------------------------------------------

    "search_youtube",

    "search_and_play_youtube",


    # --------------------------------------------------------
    # SISTEMA
    # --------------------------------------------------------

    "get_time",

    "run_cmd",


    # --------------------------------------------------------
    # SPOTIFY
    # --------------------------------------------------------

    "play_spotify",


    # --------------------------------------------------------
    # CÁMARA
    # --------------------------------------------------------

    "start_camera",
}


# ============================================================
# EJECUTOR SEGURO
# ============================================================

def execute_safely(
    tool_name,
    arguments=None
):

    # --------------------------------------------------------
    # VERIFICAR SI LA HERRAMIENTA ESTÁ PERMITIDA
    # --------------------------------------------------------

    if tool_name not in ALLOWED_TOOLS:

        return (
            "Acción bloqueada. "
            "La herramienta no está permitida."
        )


    # --------------------------------------------------------
    # EJECUTAR HERRAMIENTA
    # --------------------------------------------------------

    return execute_tool(
        tool_name,
        arguments
    )